/** 'C10', '10', 'C1012' → 업종 태그. 표에 없으면 null (모름) */
export function industryTagsForKsic(code: string | null): string[] | null {
  if (!code) return null
  const digits = code.trim().toUpperCase().replace(/^[A-Z]/, '')
  if (!/^\d{2,5}$/.test(digits)) return null
  for (let len = digits.length; len >= 2; len -= 1) {
    const tags = KSIC_INDUSTRY_TAGS[digits.slice(0, len)]
    if (tags) return [...tags]
  }
  return null
}

/** KSIC 대분류가 C(제조업, 중분류 10~34)인지 */
export function isManufacturingKsic(code: string | null): boolean | null {
  if (!code) return null
  const digits = code.trim().toUpperCase().replace(/^[A-Z]/, '')
  if (!/^\d{2,5}$/.test(digits)) return null
  const division = Number(digits.slice(0, 2))
  return division >= 10 && division <= 34
}
