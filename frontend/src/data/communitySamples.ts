import type { CommunityPost, InfoCategory, ReviewCategory } from '@/types/community'

const ANONYMOUS = { kind: 'nickname', label: '익명', participationVerified: false } as const

interface Seed<C> {
  category: C
  title: string
  body: string
  createdAt: string
}

function build<C extends ReviewCategory | InfoCategory>(
  board: 'reviews' | 'info',
  prefix: string,
  seeds: Seed<C>[],
): CommunityPost[] {
  return seeds.map((seed, index) => ({
    id: `${prefix}${String(index + 1).padStart(2, '0')}`,
    board,
    category: seed.category,
    title: seed.title,
    body: seed.body,
    author: { ...ANONYMOUS },
    programId: null,
    programYear: null,
    programRound: null,
    operatorName: null,
    reviewAnswers: null,
    status: 'published',
    isNotice: false,
    viewCount: 0,
    likeCount: 0,
    commentCount: 0,
    createdAt: seed.createdAt,
    updatedAt: seed.createdAt,
  }))
}

